/// 上書き確認ダイアログのドメイン enum。
///
/// #40（SFTP ダウンロード）と #41（ファイルアップロード）が別々に
/// 「上書き/リネーム/スキップ」「上書き/リネーム/キャンセル」を実装予定だった
/// ことから、両者の選択肢を 1 つの enum で表現する（共通基盤・項目4）。
///
/// 呼び出し規約:
/// - null 許容: ダイアログの戻り値は null を返し得る（barrier/back dismiss = 操作中断）
/// - 失敗: throw しない（結果値で返す）
/// - sync/async: `showOverwriteConfirmDialog` は async
/// - 副作用: ダイアログ表示のみ（決定の適用は呼び出し側 #40/#41 の責務）
enum OverwriteChoice {
  /// 同名ファイルを上書きする。
  overwrite,

  /// ファイル名を変えて保存/転送する。
  rename,

  /// そのファイルだけスキップして他は継続する（#40 batch 向け）。
  skip,

  /// 転送全体を中止する（#41 single 向け）。
  cancel,
}

/// 上書き確認ダイアログの表示モード。
///
/// UI に出す選択肢は以下のとおり切り替わる:
/// - [batch]: 上書き / リネーム / スキップ（+ 全ファイル適用オプション・#40）
/// - [single]: 上書き / リネーム / キャンセル（#41）
enum OverwriteDialogMode { batch, single }
